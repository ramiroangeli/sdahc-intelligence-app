// Builds api/_lib/vendor/listings-core.mjs from a checkout of the website repo, so the Listings Manager applies the SAME
// address, price, slug, safety and publication rules as the website build, without a second hand-written copy.
//   node scripts/vendor-listings-core.mjs --from /path/to/sdahc-website
// The website modules import `astro/zod`; here that import is aliased to the zod package and inlined, so the output has
// no runtime dependency. The output records the source commit. Rebuild when the website rules change.
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { createRequire } from 'node:module';

const from = process.argv[process.argv.indexOf('--from') + 1];
if (!from || from.startsWith('--')) { console.error('usage: node scripts/vendor-listings-core.mjs --from <website checkout>'); process.exit(2); }
const src = resolve(from, 'src/data/listings');
const commit = execFileSync('git', ['-C', resolve(from), 'rev-parse', 'HEAD']).toString().trim();
const dirty = execFileSync('git', ['-C', resolve(from), 'status', '--porcelain', '--', 'src/data/listings']).toString().trim();
if (dirty) { console.error('The website listings folder has uncommitted changes. Build from a clean checkout.'); process.exit(1); }

const entry = join(mkdtempSync(join(tmpdir(), 'lc-')), 'entry.ts');
writeFileSync(entry, `
export { parsePublicAddress, makeSlug, formatPublicAddress, AddressError } from '${src}/address';
export { normalisePriceDisplay, pricingLine } from '${src}/pricing';
export { publicContentSchema, optionalGroupsSchema, propertySchema, investmentSchema, marketingSchema, DESIGN_LABEL, PRICING_MODE_LABEL, STATES, PRICING_MODES, DESIGN_CATEGORIES, LEASE_STATUSES, OCCUPANCY_STATUSES, INCOME_TYPES, FIGURE_BASES, LEASE_LABEL, OCCUPANCY_LABEL } from '${src}/schema';
export { investmentValuesHash, investmentApprovalValid, hasFinancialFigures, VICTORIAN_FINANCIAL_RESTRICTION } from '${src}/investment';
export { AGENCIES, DEFAULT_AGENCY_KEY, isApprovedAgency } from '${src}/agencies';
export { validateForPublication, contentHash } from '${src}/versioning';
export { checkPublicSafety, findFinancialMentions } from '${src}/guards';
export { descriptionBlocks, parseDescription, splitIntro, firstParagraph } from '${src}/description';
`);
const zod = createRequire(import.meta.url).resolve('zod');
await build({
  entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile: 'api/_lib/vendor/listings-core.mjs', logLevel: 'error',
  alias: { 'astro/zod': zod }, define: { 'import.meta.env.DEV': 'false' },
  banner: { js: `// GENERATED by scripts/vendor-listings-core.mjs. Do not edit.\n// Source: ramiroangeli/sdahc-website src/data/listings @ ${commit}\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);` },
});
console.log(`api/_lib/vendor/listings-core.mjs built from website commit ${commit}`);
